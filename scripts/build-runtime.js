"use strict";

// 发布入口构建器：把固定的源码白名单打包成自包含单文件 CommonJS index.js。
// 只读取清单内的相对路径；不执行用户模块、不访问用户目录、不写入除目标文件外的任何内容。
// 输出对同一输入必须 byte-identical：不含时间戳、随机值或环境相关信息。

const fs = require("node:fs");
const path = require("node:path");

const PROJECT_ROOT = path.resolve(__dirname, "..");

// 固定的源码白名单：模块 id 为相对项目根的 POSIX 路径，顺序即打包顺序。
const MODULE_ORDER = Object.freeze([
  "src/voice-value.js",
  "src/text.js",
  "src/wav.js",
  "src/http-client.js",
  "src/catalog.js",
  "src/backends/audio8.js",
  "src/backends/gpt-sovits.js",
  "src/backends/index.js",
  "src/plugin.js",
]);

const ENTRY_MODULE = "src/plugin.js";

function readModules() {
  const modules = [];
  for (const id of MODULE_ORDER) {
    const absolute = path.join(PROJECT_ROOT, id);
    const stats = fs.lstatSync(absolute);
    if (stats.isSymbolicLink() || !stats.isFile()) {
      throw new Error(`build-runtime: source entry must be a regular file: ${id}`);
    }
    const source = rewriteRequires(stripTestHooks(fs.readFileSync(absolute, "utf8"), id), id);
    modules.push({ id, source });
  }
  return modules;
}

function resolveModuleId(fromId, request) {
  const base = fromId.slice(0, fromId.lastIndexOf("/") + 1);
  const parts = [];
  for (const segment of (base + request).split("/")) {
    if (segment === "" || segment === ".") {
      continue;
    }
    if (segment === "..") {
      parts.pop();
      continue;
    }
    parts.push(segment);
  }
  return parts.join("/");
}

// 把项目内部的相对 require 静态解析成模块 id，把其余请求指向 Node 标准库/内置 require，
// 于是发布包里不存在任何相对 require，也没有运行时路径解析。
function rewriteRequires(source, id) {
  return source.replace(/require\(\s*(["'])([^"']+)\1\s*\)/g, (full, quote, request) => {
    if (request.startsWith(".")) {
      const target = resolveModuleId(id, request);
      if (!MODULE_ORDER.includes(target)) {
        throw new Error(`build-runtime: ${id} requires a module outside the whitelist: ${request}`);
      }
      return `__require(${JSON.stringify(target)})`;
    }
    return `__nodeRequire(${JSON.stringify(request)})`;
  });
}

// 发布包不得包含内部测试缝：只从导出块里移除 __testHooks 属性（含其前导说明注释），
// 不改动任何已验收源文件本身，也不影响其它导出。
function stripTestHooks(source, id) {
  const lines = source.split("\n");
  const kept = [];
  let index = 0;

  while (index < lines.length) {
    const line = lines[index];
    const match = /^(\s*)__testHooks:\s*(\{.*)?$/.exec(line);
    if (!match) {
      kept.push(line);
      index += 1;
      continue;
    }

    const indent = match[1];
    // 移除紧贴在属性上方、说明仅供测试使用的注释行。
    while (kept.length > 0 && /仅供测试/.test(kept[kept.length - 1])) {
      kept.pop();
    }

    if (/(\}\s*,)\s*$/.test(line)) {
      index += 1;
      continue;
    }

    const closing = `${indent}},`;
    index += 1;
    while (index < lines.length && lines[index] !== closing) {
      index += 1;
    }
    if (index >= lines.length) {
      throw new Error(`build-runtime: unterminated __testHooks block in ${id}`);
    }
    index += 1;
  }

  const stripped = kept.join("\n");
  if (stripped.includes("__testHooks")) {
    throw new Error(`build-runtime: module ${id} still references __testHooks`);
  }
  return stripped;
}

function buildBundle(modules) {
  const factories = modules
    .map(
      (mod) =>
        `  ${JSON.stringify(mod.id)}: function (module, exports) {\n${mod.source.replace(/^(?=.)/gm, "    ")}\n  },`,
    )
    .join("\n");

  return `"use strict";

// Generated by scripts/build-runtime.js. Do not edit by hand.
// Self-contained CommonJS entry: module.exports = { default, getEditorOptions }.

const __nodeRequire = require;

const __modules = {
${factories}
};

const __cache = Object.create(null);

function __require(id) {
  const cached = __cache[id];
  if (cached) {
    return cached.exports;
  }
  const factory = __modules[id];
  if (typeof factory !== "function") {
    throw new Error("build-runtime: module is not in the static whitelist: " + id);
  }
  const module = { exports: {} };
  __cache[id] = module;
  factory(module, module.exports);
  return module.exports;
}

module.exports = __require(${JSON.stringify(ENTRY_MODULE)});
`;
}

function main(argv) {
  const args = argv.slice(2);
  let outputPath = path.join(PROJECT_ROOT, "index.js");
  let toStdout = false;

  for (let index = 0; index < args.length; index += 1) {
    const arg = args[index];
    if (arg === "--output") {
      const value = args[index + 1];
      if (!value) {
        throw new Error("build-runtime: --output requires a path");
      }
      outputPath = path.resolve(value);
      index += 1;
    } else if (arg === "--stdout") {
      toStdout = true;
    } else if (arg === "-h" || arg === "--help") {
      process.stdout.write("Usage: build-runtime.js [--output PATH] [--stdout]\n");
      return 0;
    } else {
      throw new Error(`build-runtime: unknown argument ${arg}`);
    }
  }

  const bundle = buildBundle(readModules());

  if (toStdout) {
    process.stdout.write(bundle);
    return 0;
  }

  const existing = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : null;
  if (existing === bundle) {
    process.stdout.write(`build-runtime: unchanged ${outputPath}\n`);
    return 0;
  }

  fs.writeFileSync(outputPath, bundle, "utf8");
  process.stdout.write(`build-runtime: wrote ${outputPath}\n`);
  return 0;
}

if (require.main === module) {
  try {
    process.exitCode = main(process.argv);
  } catch (error) {
    process.stderr.write(`${error.message}\n`);
    process.exitCode = 1;
  }
}

module.exports = {
  MODULE_ORDER,
  ENTRY_MODULE,
  buildBundle,
  readModules,
  stripTestHooks,
  rewriteRequires,
  resolveModuleId,
};
